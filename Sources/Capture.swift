import AppKit

/// Polls the system clipboard and records every change, including Universal Clipboard copies from iPhone.
final class Capture {
    private let db = DB()
    private let queue = DispatchQueue(label: "clipbubble.capture")
    private let board: NSPasteboard
    private var count: Int
    private var seenCount: Int
    private var seenAt = Date()
    /// The latest capture and the one before it, to spot tools that paste through the clipboard.
    private var last: (hash: String, at: Date, inserted: Bool)?
    private var previousHash: String?
    private var timer: DispatchSourceTimer?
    private let onChange: (_ copied: Bool) -> Void

    /// The pasteboard change ClipBubble made itself, and the item it put there: another device's copy, or a pick from history.
    /// Capturing it would bounce the copy back, or take a pick of the previous item for a paste-through.
    private static let skipLock = NSLock()
    private static var ownChange: (count: Int, hash: String)?
    static func ignoreChange(_ changeCount: Int, hash: String) { skipLock.lock(); ownChange = (changeCount, hash); skipLock.unlock() }
    private static func ownWrite(_ changeCount: Int) -> String? {
        skipLock.lock(); defer { skipLock.unlock() }
        return ownChange?.count == changeCount ? ownChange?.hash : nil
    }

    /// Password managers and other tools mark secrets and throwaway copies with these; never record them.
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]
    /// Text bigger than this (a log dump, a database export) isn't kept: it would slow every list and search.

    /// `copied` is false when history changed but nothing new was copied: a paste-through was undone.
    init(board: NSPasteboard = .general, onChange: @escaping (_ copied: Bool) -> Void) {
        self.board = board
        count = board.changeCount
        seenCount = count
        self.onChange = onChange
        let t = DispatchSource.makeTimerSource(queue: queue)
        t.schedule(deadline: .now(), repeating: 0.4)
        t.setEventHandler { [weak self] in self?.poll() }
        t.resume()
        timer = t
    }

    private func poll() {
        let pb = board
        let now = Date()
        // Let the clipboard settle first. Paste-through tools like Wispr Flow put text on it, press ⌘V and then
        // restore the old contents; reading during that window could make them paste the wrong thing.
        if pb.changeCount != seenCount { seenCount = pb.changeCount; seenAt = now; return }
        guard seenCount != count, now.timeIntervalSince(seenAt) >= 0.6 else { return }
        count = seenCount
        if let own = Self.ownWrite(count) { last = (own, now, false); previousHash = nil; return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.skipTypes), let clip = read(pb) else { return }
        let polished = clip.kind == "image" && types.contains(Board.polishedType.rawValue)
        // The same copy again is a no-op unless it was deleted or needs the Polished source.
        if clip.hash == last?.hash,
           polished ? db.clip(hash: clip.hash)?.source == "Polished" : db.exists(hash: clip.hash) { return }
        let source: String
        if polished { source = "Polished" }
        else if types.contains("com.apple.is-remote-clipboard") { source = "iPhone" }
        else { source = NSWorkspace.shared.frontmostApplication?.localizedName ?? "Mac" }
        let category = source == "iPhone" ? "iphone" : (["image": "images", "file": "files"][clip.kind] ?? "text")
        guard Prefs.on(category) else { return }
        if source == "iPhone", clip.kind == "file", Self.isEcho(clip.text.components(separatedBy: "\n"), db: db) { return }

        // The previous contents came straight back, so what we just saw was a paste-through: drop it,
        // and don't bump the restored item.
        if !polished, clip.hash == previousHash, let l = last, now.timeIntervalSince(l.at) < 2.5 {
            if l.inserted { db.delete(hash: l.hash) }
            last = (clip.hash, now, false)
            previousHash = nil
            onChange(false)
            return
        }

        if let png = clip.png, let path = clip.file, !FileManager.default.fileExists(atPath: path) {
            FileManager.default.createFile(atPath: path, contents: png)
        }
        let inserted = !db.exists(hash: clip.hash)
        db.upsert(kind: clip.kind, text: clip.text, file: clip.file, source: source, hash: clip.hash)
        previousHash = polished ? nil : last?.hash
        last = (clip.hash, now, inserted)
        onChange(true)
    }

    /// Universal Clipboard hands over a file under a new path each time, so it would be a new item with a new hash.
    /// When its bytes match a recent item's file, it's that item coming back (often ClipBubble's own write on the
    /// other Mac); recording it would sync it back there as new, and round again.
    static func isEcho(_ paths: [String], db: DB) -> Bool {
        let recent = db.clips(limit: 200, kind: "file", sinceHours: 1).filter { !$0.remote }.flatMap(\.paths)
        return !paths.isEmpty && paths.allSatisfy { p in recent.contains { $0 != p && sameBytes($0, p) } }
    }

    /// What's on the clipboard. An image isn't written anywhere yet: Copied images might be off.
    private func read(_ pb: NSPasteboard) -> (kind: String, text: String, file: String?, hash: String, png: Data?)? {
        let string = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let looksLikeURL = string.map { !$0.contains(" ") && !$0.contains("\n") && $0.hasPrefix("http") } ?? false

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return ("file", paths, nil, "f:" + sha(paths), nil)
        }
        if string?.isEmpty ?? true || looksLikeURL, let png = imagePNG(pb) {
            let h = sha(png)
            return ("image", "", Paths.images.appendingPathComponent(h + ".png").path, "i:" + h, png)
        }
        if let raw = pb.string(forType: .string), !(string?.isEmpty ?? true), raw.utf8.count <= Sync.maxText {
            return ("text", raw, nil, "t:" + sha(raw), nil)
        }
        return nil
    }

    private func imagePNG(_ pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        for t in [NSPasteboard.PasteboardType.tiff, .init("public.jpeg"), .init("public.heic")] {
            if let d = pb.data(forType: t), let rep = NSBitmapImageRep(data: d) {
                return rep.representation(using: .png, properties: [:])
            }
        }
        return nil
    }
}

/// Watches a folder (screenshots, Downloads) and hands each new item that passes `include` to `onNew`.
final class FolderWatcher {
    static let tempExts: Set<String> = ["crdownload", "download", "part", "partial", "tmp", "opdownload", "icloud"]
    /// Where macOS saves screenshots (⌘⇧5 → Options → Save to), or the Desktop if that's never been set.
    static var macOSScreenshotFolder: URL {
        let raw = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location") ?? "~/Desktop"
        return URL(fileURLWithPath: (raw as NSString).expandingTildeInPath, isDirectory: true)
    }
    /// A folder picked in Settings wins over the macOS setting.
    static var screenshotFolder: URL {
        if let custom = UserDefaults.standard.string(forKey: "screenshotFolder"), !custom.isEmpty {
            return URL(fileURLWithPath: custom, isDirectory: true)
        }
        return macOSScreenshotFolder
    }
    static var downloadsFolder: URL? { FileManager.default.urls(for: .downloadsDirectory, in: .userDomainMask).first }

    static func isScreenCapture(_ url: URL) -> Bool {
        getxattr(url.path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) >= 0
    }

    /// Whether we can read the folder (asks macOS the first time, which may show its privacy prompt).
    static func canRead(_ url: URL?) -> Bool {
        guard let url else { return false }
        return (try? FileManager.default.contentsOfDirectory(atPath: url.path)) != nil
    }

    let folder: URL
    private let include: (URL) -> Bool
    private let maxAge: TimeInterval?
    private let onNew: (URL, Date) -> Void
    private let openFolder: (URL) throws -> Int32
    private let list: (URL) throws -> [URL]
    private let onAccessChanged: (Bool) -> Void
    private let retryDelay: TimeInterval
    private let queue = DispatchQueue(label: "clipbubble.folder", qos: .utility)
    private let lifecycle = NSLock()
    private var cancelled = false
    private var stopped: Bool { lifecycle.withLock { cancelled } }
    private var known: Set<URL> = []
    private var seenFiles: Set<PolishedFile> = []
    private var source: DispatchSourceFileSystemObject?
    private var pending: DispatchWorkItem?
    private var since: Date? = Date()
    private var paused = false
    private var canAccess: Bool?
    private var nextRetryDelay: TimeInterval

    /// `maxAge` ignores files older than that (so moving old screenshots in doesn't count); nil takes everything new.
    init(folder: URL, maxAge: TimeInterval?, include: @escaping (URL) -> Bool,
         retryDelay: TimeInterval = 5, openFolder: @escaping (URL) throws -> Int32 = FolderWatcher.openFolder,
         list: @escaping (URL) throws -> [URL] = FolderWatcher.listFiles,
         onAccessChanged: @escaping (Bool) -> Void = { _ in }, onNew: @escaping (URL, Date) -> Void) {
        self.folder = folder
        self.maxAge = maxAge
        self.include = include
        self.retryDelay = retryDelay
        self.nextRetryDelay = retryDelay
        self.openFolder = openFolder
        self.list = list
        self.onAccessChanged = onAccessChanged
        self.onNew = onNew
        queue.async { [weak self] in self?.start() }
    }

    deinit { source?.cancel() }

    func stop() {
        lifecycle.withLock { cancelled = true }
        queue.async { self.stopWatching() }
    }

    func retryIfPaused() {
        queue.async { [weak self] in
            guard let self, !self.stopped, self.paused else { return }
            self.paused = false
            self.start()
        }
    }

    private func stopWatching() {
        pending?.cancel()
        pending = nil
        source?.cancel()
        source = nil
    }

    private func start() {
        guard !stopped else { return }
        let fd: Int32
        do { fd = try openFolder(folder) } catch {
            handleFailure(error)
            return
        }
        let src = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: [.write, .rename, .delete], queue: queue)
        src.setEventHandler { [weak self, weak src] in
            guard let self, let src, self.source === src, !self.stopped else { return }
            // The folder itself moved or vanished: the old handle is dead, so watch the path afresh.
            if !src.data.isDisjoint(with: [.rename, .delete]) {
                self.stopWatching()
                self.since = Date()
                self.schedule(after: 1) { $0.start() }
                return
            }
            self.scheduleScan()
        }
        src.setCancelHandler { close(fd) }
        source = src
        // Arm the watch before taking the first snapshot so writes during that read still trigger a scan.
        src.activate()
        do {
            try scan()
            scheduleScan()
        } catch {
            handleFailure(error)
        }
    }

    private func scheduleScan() {
        schedule(after: 0.4) { watcher in
            do { try watcher.scan() } catch { watcher.handleFailure(error) }
        }
    }

    private func schedule(after delay: TimeInterval, _ action: @escaping (FolderWatcher) -> Void) {
        guard !stopped else { return }
        pending?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self, !self.stopped else { return }
            self.pending = nil
            action(self)
        }
        pending = work
        queue.asyncAfter(deadline: .now() + delay, execute: work)
    }

    private func handleFailure(_ error: Error) {
        stopWatching()
        reportAccess(false)
        let error = error as NSError
        if (error.domain == NSPOSIXErrorDomain && (error.code == Int(EPERM) || error.code == Int(EACCES)))
            || (error.domain == NSCocoaErrorDomain && error.code == NSFileReadNoPermissionError) {
            paused = true
            nextRetryDelay = retryDelay
            return
        }
        let delay = nextRetryDelay
        nextRetryDelay = min(delay * 2, 60)
        schedule(after: delay) { $0.start() }
    }

    private func reportAccess(_ allowed: Bool) {
        guard canAccess != allowed else { return }
        canAccess = allowed
        deliver { $0.onAccessChanged(allowed) }
    }

    static func added(_ u: URL) -> Date {
        let v = try? u.resourceValues(forKeys: [.addedToDirectoryDateKey, .creationDateKey])
        return v?.addedToDirectoryDate ?? v?.creationDate ?? .distantPast
    }

    /// For recency-gated folders (screenshots), require both directory-addition and file creation to be recent,
    /// so old screenshots moved or re-synced onto Desktop (e.g. by iCloud) never appear as newly captured.
    static func recencyDate(_ u: URL) -> Date {
        let v = try? u.resourceValues(forKeys: [.addedToDirectoryDateKey, .creationDateKey])
        switch (v?.addedToDirectoryDate, v?.creationDate) {
        case let (a?, c?): return min(a, c)
        case let (a?, nil): return a
        case let (nil, c?): return c
        case (nil, nil): return .distantPast
        }
    }

    /// Everything already in the folder from the last `days` days, for backfilling history.
    func existing(days: Double, done: @escaping ([(URL, Date)]) -> Void) {
        queue.async { [weak self] in
            guard let self, !self.stopped, self.source != nil else { return }
            let cutoff = Date().addingTimeInterval(-days * 86400)
            do {
                let found = try self.list(self.folder).filter(self.include).map { ($0, Self.added($0)) }.filter { $0.1 > cutoff }
                self.deliver { _ in done(found) }
            } catch {
                self.handleFailure(error)
            }
        }
    }

    static func openFolder(_ folder: URL) throws -> Int32 {
        let fd = open(folder.path, O_EVTONLY | O_CLOEXEC)
        guard fd >= 0 else { throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno)) }
        return fd
    }

    static func listFiles(_ folder: URL) throws -> [URL] {
        try FileManager.default.contentsOfDirectory(
            at: folder, includingPropertiesForKeys: [.creationDateKey, .addedToDirectoryDateKey], options: [.skipsHiddenFiles])
    }

    private func scan() throws {
        let urls = try list(folder)
        guard !stopped else { return }
        let now = urls.filter(include)
        let identities = Dictionary(uniqueKeysWithValues: now.compactMap { url in
            PolishedFile.read(url).map { (url, $0) }
        })
        let fresh = since == nil ? now.filter { url in
            if let id = identities[url] { return !seenFiles.contains(id) }
            return !known.contains(url)
        } : now.filter { url in
            if let id = identities[url] { return !seenFiles.contains(id) }
            return true
        }
        known = Set(now)
        seenFiles.formUnion(identities.values)
        let cutoff = max(since ?? .distantPast, maxAge.map { Date().addingTimeInterval(-$0) } ?? .distantPast)
        since = nil
        nextRetryDelay = retryDelay
        reportAccess(true)
        let added = fresh.compactMap { url -> (URL, Date)? in
            let date = Self.added(url)
            let checkDate = maxAge == nil ? date : Self.recencyDate(url)
            return checkDate >= cutoff ? (url, date) : nil
        }.sorted { $0.1 < $1.1 }
        if !added.isEmpty {
            deliver { watcher in
                for (url, date) in added where !watcher.stopped {
                    watcher.onNew(url, watcher.maxAge == nil ? Date() : date)
                }
            }
        }
    }

    private func deliver(_ action: @escaping (FolderWatcher) -> Void) {
        DispatchQueue.main.async { [weak self] in
            guard let self, !self.stopped else { return }
            action(self)
        }
    }
}
